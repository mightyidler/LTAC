const entries = rules.map(([selector, component, text]) => ({ selector, ...source(component, text) }));
const roles = { Regular: 'body', Medium: 'copy', SemiBold: 'heading' };
const tokens = Object.entries(originalWeights).map(([style, rawWeight]) => `  --font-weight-${roles[style]}: ${rawWeight - 100}; /* JSON ${style} ${rawWeight} - 100, once */`).join('\n');
const lightTokens = Object.entries(originalWeights).map(([style, rawWeight]) => `  --font-weight-${roles[style]}: ${rawWeight}; /* Base ${rawWeight - 100} + 100 for light mode */`).join('\n');
const css = `/* Generated by tools/import-typography.mjs from the original supplied JSON.\n   Do not subtract from these final values again. */\n:root {\n${tokens}\n}\n\n:root[data-theme="light"] {\n${lightTokens}\n}\n\n` + entries.map(entry => `/* ${entry.path}: ${entry.originalStyle} ${entry.originalWeight} → ${entry.weight} */\n${entry.selector} { font-weight: var(--font-weight-${roles[entry.originalStyle]}); }`).join('\n\n') + '\n';
