import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Always import RAW design data. Never derive a weight from existing CSS.
const sourcePath = process.argv[2];
if (!sourcePath) throw new Error('Usage: node tools/import-typography.mjs <original-design.json-or-txt>');
const raw = readFileSync(sourcePath, 'utf8').replace(/^\uFEFF/, '');
const design = JSON.parse(raw);
const originalWeights = { Regular: 400, Medium: 500, SemiBold: 600 };
function source(component, characters) {
  const matches = [];
  function visit(node, path) {
    const nextPath = [...path, node.name];
    if (node.type === 'TEXT' && node.characters === characters) matches.push({ node, path: nextPath });
    for (const child of node.children ?? []) visit(child, nextPath);
  }
  visit(design.components[component].node, [component]);
  if (!matches.length) throw new Error(`Missing source text: ${component} / ${characters}`);
  const styles = new Set(matches.map(({node}) => node.font?.style ?? 'Regular'));
  if (styles.size !== 1) throw new Error(`Ambiguous source style: ${component} / ${characters}`);
  const { node, path } = matches[0];
  const originalStyle = node.font.style ?? 'Regular';
  const originalWeight = originalWeights[originalStyle];
  if (!originalWeight) throw new Error(`Unknown source font style: ${originalStyle}`);
  return { component, path: path.join('/'), text: characters, originalStyle, originalWeight, weight: originalWeight - 100 };
}
